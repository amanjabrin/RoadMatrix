// Helper functions for calculations
export const getVehicleById = (id: string) => mockVehicles.find(v => v.id === id);
export const getDriverById = (id: string) => mockDrivers.find(d => d.id === id);
export const getTripsByVehicle = (vehicleId: string) => mockTrips.filter(t => t.vehicleId === vehicleId);
export const getTripsByDriver = (driverId: string) => mockTrips.filter(t => t.driverId === driverId);
export const getMaintenanceByVehicle = (vehicleId: string) => mockMaintenanceLogs.filter(m => m.vehicleId === vehicleId);
export const getFuelLogsByVehicle = (vehicleId: string) => mockFuelLogs.filter(f => f.vehicleId === vehicleId);

// Calculate total operational cost per vehicle
export const getVehicleOperationalCost = (vehicleId: string): number => {
  const maintenanceCost = mockMaintenanceLogs
    .filter(m => m.vehicleId === vehicleId && m.status === 'completed')
    .reduce((sum, m) => sum + m.cost, 0);
  
  const fuelCost = mockFuelLogs
    .filter(f => f.vehicleId === vehicleId)
    .reduce((sum, f) => sum + f.cost, 0);
  
  return maintenanceCost + fuelCost;
};

// Calculate vehicle ROI
export const getVehicleROI = (vehicleId: string): { revenue: number; costs: number; roi: number } => {
  const revenue = mockTrips
    .filter(t => t.vehicleId === vehicleId && t.status === 'completed')
    .reduce((sum, t) => sum + (t.revenue || 0), 0);
  
  const operationalCosts = getVehicleOperationalCost(vehicleId);
  const vehicle = getVehicleById(vehicleId);
  const totalCosts = operationalCosts + (vehicle?.acquisitionCost || 0);
  
  const roi = totalCosts > 0 ? ((revenue - totalCosts) / totalCosts) * 100 : 0;
  
  return { revenue, costs: totalCosts, roi };
};

// Calculate fuel efficiency (km per liter)
export const getFuelEfficiency = (vehicleId: string): number => {
  const vehicleTrips = mockTrips.filter(t => t.vehicleId === vehicleId && t.status === 'completed');
  const totalDistance = vehicleTrips.reduce((sum, t) => sum + (t.distance || 0), 0);
  
  const totalFuel = mockFuelLogs
    .filter(f => f.vehicleId === vehicleId)
    .reduce((sum, f) => sum + f.liters, 0);
  
  return totalFuel > 0 ? totalDistance / totalFuel : 0;
};
